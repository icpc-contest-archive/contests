#!/usr/bin/env python3
"""Apply problem names read from captured problem-set statements (PDF/HTML).

Input: a candidates file made by the statement-title extractors (_hunt/problems-2026-11-13/
extract_pdf_titles.py, extract_html_titles.py): {contest id: {url, path, how, flags, problems:
[{letter, name}]}}. Only candidates without flags are applied, and only to contests whose set
lists no problems yet: the set is opened when missing (count = number of problems read), the
problems get ids p-sha1(set|letter|name)[:8], and the contest's letter map is written. The
statement itself becomes a source of the contest (add_statement_sources.statement_source), so
it is not only named in the set's provenance note. Everything else is listed in the report for
ruling (shared sets, count disagreements, doubtful reads).

usage: apply_statement_titles.py <candidates.json> [--date YYYY-MM-DD] [--dry-run]
"""
from __future__ import annotations
import argparse, collections, json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from catalogue import ROOT, dump_series, load_judges, load_series, load_sets  # noqa: E402
from add_statement_sources import statement_source  # noqa: E402
from mine_judge_links import dump_set, pid  # noqa: E402

def clean(name: str) -> str:
    return name.replace("ı́", "í").strip()

def main() -> int:
    ap = argparse.ArgumentParser(); ap.add_argument("candidates"); ap.add_argument("--date", required=True)
    ap.add_argument("--dry-run", action="store_true"); ap.add_argument("--report", default=None, help="report file name under reports/ (default statement-titles-<date>.md)"); a = ap.parse_args()
    cands = json.loads(Path(a.candidates).read_text())
    series = load_series(); sets = load_sets(); judges = load_judges()
    where = {c["id"]: (sid, c) for sid, doc in series.items() for c in doc["contests"]}
    rep = collections.defaultdict(list); touched_series = set(); changed = set(); nprob = 0
    for cid, v in sorted(cands.items()):
        probs = v["problems"]; line = f"{cid}: {len(probs)} problems <- {v['url']}"
        for p in probs:
            if p["name"].endswith(",") or re.match(r"^(to|of|and|the) ", p["name"]) or re.search(r"\((?:[^()]*,){1,}[^()]*\)$", p["name"]):
                v["flags"] = v.get("flags", []) + ["truncated?"]; break
        if v.get("flags"):
            rep["held for ruling: " + v["flags"][0].split(":")[0]].append(line + "  [" + "; ".join(v["flags"]) + "]  " + " | ".join(p["name"] for p in probs))
            continue
        if cid not in where:
            rep["contest not in catalogue"].append(line); continue
        ser, c = where[cid]
        if c.get("status") == "upcoming":
            rep["contest has not run"].append(line); continue
        sid = (c.get("problems") or {}).get("set")
        if sid and sid in sets:
            s = sets[sid]
            if s.get("problems"):
                rep["set already lists problems (skipped)"].append(line); continue
            if s.get("count") and s["count"] != len(probs):
                rep["held for ruling: count"].append(line + f"  [set count {s['count']}]"); continue
        else:
            sid = cid
            if sid in sets:
                rep["set id taken by another contest (skipped)"].append(line); continue
            s = sets[sid] = {"id": sid, "contests": [{"contest": cid}], "provenance": []}
            c["problems"] = {"set": sid}; touched_series.add(ser)
        s["count"] = len(probs)
        entry = next((e for e in s["contests"] if e["contest"] == cid), None)
        if entry is None:
            entry = {"contest": cid}; s["contests"].append(entry)
        rows = []; letters = {}
        for p in probs:
            name = clean(p["name"]); i = pid(None, sid, p["letter"], name)
            rows.append({"id": i, "name": name}); letters[p["letter"]] = i
        if len({r["id"] for r in rows}) != len(rows):
            rep["id clash (skipped)"].append(line); continue
        entry["letters"] = letters; s["problems"] = rows
        s.setdefault("provenance", []).append(
            f"problem names read from the published statement {v['url']} (capture {v['path']}; "
            f"tools/apply_statement_titles.py, {a.date})")
        if statement_source(c, v["url"], judges)[1]:  # the statement is a source of the contest, not only a note on the set
            touched_series.add(ser)
        changed.add(sid); nprob += len(rows)
        rep["applied"].append(line)
    if not a.dry_run:
        for sid in changed:
            (ROOT / "problemsets" / f"{sid}.yaml").write_text(dump_set(sets[sid]))
        for ser in touched_series:
            dump_series(ser, series[ser], f"apply_statement_titles.py ({a.date})")
        out = ROOT / "reports" / (a.report or f"statement-titles-{a.date}.md")
        lines = [f"# Problem names read from captured statements — {a.date}", "",
                 f"Generated by `tools/apply_statement_titles.py` from `{a.candidates}`.", "",
                 f"- sets filled: {len(changed)}", f"- problems added: {nprob}", ""]
        for k in sorted(rep, key=lambda k: (k != "applied", k)):
            lines += [f"## {k} ({len(rep[k])})", ""] + [f"- {x}" for x in rep[k]] + [""]
        out.write_text("\n".join(lines))
    print({k: len(v) for k, v in rep.items()}, "sets", len(changed), "problems", nprob)
    return 0

if __name__ == "__main__":
    sys.exit(main())
